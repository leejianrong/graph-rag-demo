"""Export a generated world, its questions and its documents as one reproducible dataset.

The archive carries the data (``world.json``, ``questions.json``, ``documents.json``, a stats
report) and the three specs that made it, so ``kggen export`` run on those specs gives back the
same bytes. The zip is deterministic: sorted names, fixed timestamps, one compression setting.
"""

from __future__ import annotations

import io
import json
import zipfile
from dataclasses import dataclass

from kggen.questions import QuestionSpec, generate_questions
from kggen.render import RenderSpec, render_documents
from kggen.spec import WorldSpec
from kggen.stats import report
from kggen.world import World, WorldGenerationError, generate

COMMAND = (
    "kggen export --spec spec.json --questions-spec questions_spec.json "
    "--render-spec render_spec.json --out dataset.zip"
)
_EPOCH = (2020, 1, 1, 0, 0, 0)  # a fixed timestamp, so the same files always zip to the same bytes


def _json(value: object) -> bytes:
    return (json.dumps(value, sort_keys=True, indent=1) + "\n").encode()


@dataclass(frozen=True)
class Specs:
    """What made a dataset: enough to make it again."""

    world: WorldSpec
    questions: QuestionSpec
    render: RenderSpec


def export_files(world: World, questions: QuestionSpec, render: RenderSpec) -> dict[str, bytes]:
    """The dataset as ``{filename: bytes}``. A world that cannot supply the questions asked for
    still exports; ``questions.json`` is then left out and the README says why."""
    files: dict[str, bytes] = {
        "spec.json": _json(world.spec.model_dump()),
        "questions_spec.json": _json(questions.model_dump()),
        "render_spec.json": _json(render.model_dump()),
        "world.json": world.to_json().encode(),
        "world.stats.json": _json(report(world)),
        "documents.json": _json([d.to_dict() for d in render_documents(world, render)]),
    }
    note = ""
    try:
        files["questions.json"] = _json([q.to_dict() for q in generate_questions(world, questions)])
    except WorldGenerationError as exc:
        note = f"\nquestions.json is not included: {exc}\n"
    files["README.md"] = _readme(world, note).encode()
    return files


def zip_bytes(files: dict[str, bytes]) -> bytes:
    """A deterministic zip of the files."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for name in sorted(files):
            info = zipfile.ZipInfo(name, date_time=_EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, files[name])
    return buffer.getvalue()


def export_archive(world: World, questions: QuestionSpec, render: RenderSpec) -> bytes:
    return zip_bytes(export_files(world, questions, render))


def reproduce(specs: Specs) -> dict[str, bytes]:
    """Make the dataset again from its specs."""
    return export_files(generate(specs.world), specs.questions, specs.render)


# What each file in the archive is, for the README table.
_FILES: tuple[tuple[str, str], ...] = (
    (
        "world.json",
        "The ground truth: `entities` (id, name, type, community, aliases, distractor) and "
        "`edges`, "
        "the facts (id, subject, predicate, object, valid_from, valid_to). `valid_to` is null "
        "while a fact still holds.",
    ),
    (
        "questions.json",
        "Questions: `question`, `type` (entity, set, count, compare, superlative, unanswerable, "
        "false_premise), `hops`, "
        "`answer` (an entity id; empty for a set or count), `answers` (every correct entity id), "
        "`number` (a count's answer), `accepted_answers` (names and aliases), `supporting_facts` "
        "(fact ids in hop order: the first gold path) and `gold_paths` (one fact chain per "
        "correct answer), `answer_kind` and `grading` (how to score it), and for the two declining "
        "types `abstain` and (for a false premise) `premise` with the contradicting fact and the "
        "correction.",
    ),
    (
        "documents.json",
        "Template documents. Each has `sentences`; each sentence names the `fact_ids` it expresses "
        "and its entity `mentions` (character offsets into the document `text`).",
    ),
    ("world.stats.json", "What the world realised against each knob in the spec."),
    (
        "spec.json, questions_spec.json, render_spec.json",
        "The three specs that made this dataset.",
    ),
)


def _readme(world: World, note: str) -> str:
    spec = world.spec
    table = "\n".join(f"| `{name}` | {what} |" for name, what in _FILES)
    return (
        "# kggen dataset\n\n"
        "A synthetic knowledge graph with questions and documents derived from it, generated by "
        f"kggen (seed {spec.seed}, {spec.n_entities:,} entities). Everything here comes from the "
        "world model; none of it is the output of any pipeline.\n\n"
        f"## Files\n\n| File | What it is |\n|------|------------|\n{table}\n\n"
        f"## Make it again\n\nThe same specs give the same bytes:\n\n```\n{COMMAND}\n```\n{note}"
    )
